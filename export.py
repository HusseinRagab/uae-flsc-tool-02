def _status_totals(r: ComplianceReport) -> dict:
    tot = {s: 0 for s in STATUS_ORDER}
    for ch in r.chapters:
        for blk in ch.blocks:
            for it in blk.items:
                tot[it.status] = tot.get(it.status, 0) + 1
    return tot


def _all_chapters(r: ComplianceReport):
    """Yield (prefix, chapter) for the main report plus the attached-parking
    sub-evaluation (prefixed 'P-'), so exports match the on-screen report."""
    for ch in r.chapters:
        yield "", ch
    for ch in getattr(r, "attached_parking_chapters", None) or []:
        yield "P-", ch


def _required_systems(ch) -> List[Requirement]:
    """Unique required-system headers for one chapter (compact view)."""
    seen, items = set(), []
    for blk in ch.blocks:
        for it in blk.items:
            if it.status != "required" or it.system in seen:
                continue
            seen.add(it.system)
            items.append(it)
    return items


def _chapter_counts(ch) -> dict:
    counts = {s: 0 for s in STATUS_ORDER}
    for blk in ch.blocks:
        for it in blk.items:
            counts[it.status] = counts.get(it.status, 0) + 1
    counts["total"] = sum(counts[s] for s in STATUS_ORDER)
    return counts


def _profile_rows(r: ComplianceReport, detailed: bool = False) -> list:
    b = r.building
    occ_label = OCCUPANCY_DEFS.get(b.occupancy, b.occupancy).split(" - ")[0]
    hc = str(b.height_class).replace("_", " ")
    rows = [
        ("Occupancy", occ_label),
        ("Height class", f"{b.height_m:g} m  |  {hc}"),
        ("Storeys", f"{b.floors_above_grade} above grade  |  {b.floors_below_grade} basement"),
        ("Gross floor area", f"{b.gross_floor_area_m2:,.0f} m²"),
        ("GF / basement BUA", f"{b.ground_floor_bua_m2:,.0f} m²  |  {b.basement_bua_m2:,.0f} m²"),
        ("Plot area", f"{b.plot_area_m2:,.0f} m²"),
        ("Hazard class", b.hazard_class),
    ]
    if detailed:
        datum = ("Lowest grade / Fire Service access"
                 if getattr(b, "height_datum", "grade") == "grade"
                 else "Occupiable ceiling")
        rows.insert(2, ("Height datum", datum))
        if r.occupant_load:
            rows.append(("Occupant load", _ol_text(r.occupant_load)))
        if r.fire_access:
            rows.append(("Fire service access",
                         f"{r.fire_access.extent}  |  {r.fire_access.extent_ref}"))
        if getattr(b, "construction_type", "unspecified") != "unspecified":
            rows.append(("Construction type", b.construction_type.replace("_", " ").title()))
    if b.has_high_ceiling:
        rows.append(("High ceiling", f"{b.ceiling_height_m:g} m"))
    if r.requires_wet_riser:
        rows.append(("Wet riser standpipes", str(b.wet_riser_standpipes)))
    return rows


def _ol_text(ol) -> str:
    """Occupant load row. Not evaluated (villa; no Table 3.13 row and no per-use areas):
    no exit count is printed (owner ruling 12.10.2026, Ch3 Q2)."""
    if not ol.evaluated or not ol.occupant_load:
        return f"not evaluated  ({ol.exit_ref})"
    basis = ("whole-building OL" if ol.storey_area_m2 == ol.area_m2 else "largest storey OL")
    return (f"{ol.occupant_load:,} persons  ->  >= {ol.min_exits} exits (Table 3.14 on the "
            f"{basis} {ol.storey_occupant_load:,})")


def _profile_rows_exec(r: ComplianceReport) -> list:
    """Condensed profile for the one-page executive summary."""
    b = r.building
    occ_label = OCCUPANCY_DEFS.get(b.occupancy, b.occupancy).split(" - ")[0]
    hc = str(b.height_class).replace("_", " ")
    rows = [
        ("Occupancy", occ_label),
        ("Height class", f"{b.height_m:g} m  |  {hc}"),
        ("Storeys", f"{b.floors_above_grade} above grade  |  {b.floors_below_grade} basement"),
        ("Gross floor area", f"{b.gross_floor_area_m2:,.0f} m²"),
        ("Hazard class", b.hazard_class),
    ]
    if r.occupant_load:
        rows.append(("Occupant load", _ol_text(r.occupant_load)))
    if r.fire_access:
        rows.append(("Fire service access", r.fire_access.extent))
    return rows


def _required_headers(r, limit=20):
    rows = []
    for ch in r.chapters:
        seen = set()
        for blk in ch.blocks:
            for it in blk.items:
                if it.status != "required" or it.system in seen:
                    continue
                seen.add(it.system)
                rows.append((ch.chapter_code, it.system, it.spec or "", it.code_ref or ""))
                if len(rows) >= limit:
                    return rows
    return rows


def _high_ceiling_rows(hc) -> list:
    return [
        ("Ceiling height", f"{hc.ceiling_height_m} m"),
        ("Hazard class", hc.hazard_class),
        ("Height band", hc.height_range or "out of tabulated range"),
        ("K-factor", hc.k_factor or "-"),
        ("Min pressure", hc.min_pressure or "-"),
        ("Min sprinklers", str(hc.min_sprinklers) if hc.min_sprinklers else "-"),
        ("Density", hc.density or "-"),
        ("Design area", hc.design_area or "-"),
        ("Pump (no hydrant)", f"{hc.pump_without_hydrant_gpm} gpm" if hc.pump_without_hydrant_gpm else "-"),
        ("Pump (with hydrant)", f"{hc.pump_with_hydrant_gpm} gpm" if hc.pump_with_hydrant_gpm else "-"),
    ]


