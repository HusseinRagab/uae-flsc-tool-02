def _detailed_docx(r: ComplianceReport, m: dict) -> bytes:
    from docx.shared import Pt, RGBColor

    doc = _docx_base(r, "detailed", m)
    tot = _status_totals(r)

    _docx_section_head(doc, "Building profile")
    _docx_kv_table(doc, _profile_rows(r, detailed=True))
    _docx_project_blocks(doc, m)

    _docx_section_head(doc, "Requirement counts")
    _docx_status_chips(doc, tot)

    def req_table(items: List[Requirement]):
        t = doc.add_table(rows=1, cols=4)
        _docx_table_borders(t, RULE_HEX, size=4)
        _docx_fixed_layout(t, _DET_W)
        hdr = t.rows[0].cells
        for cell, text in zip(hdr, ("System", "Status", "Spec / Detail", "Code Ref")):
            _docx_shade(cell, TEAL_HEX)
            _docx_set(cell, text, size=8.5, bold=True, color="FFFFFF")
        for i, req in enumerate(items):
            row = t.add_row().cells
            if i % 2 == 1:
                for cell in row:
                    _docx_shade(cell, PAPER_TINT_HEX)
            # System + colored status tag
            row[0].text = ""
            p = row[0].paragraphs[0]
            run = p.add_run(req.system)
            run.bold = True
            run.font.size = Pt(8.5)
            run.font.color.rgb = RGBColor.from_string(INK_HEX)
            # Status column on every line (audit UX-12)
            _docx_set(row[1], _status_label(req.status), size=7.5, bold=True,
                      color=_status_hex(req.status))
            # Spec / detail
            row[2].text = ""
            sp = row[2].paragraphs[0]
            if req.spec:
                lead = sp.add_run("Spec: ")
                lead.bold = True
                lead.font.size = Pt(8.5)
                lead.font.color.rgb = RGBColor.from_string(INK_HEX)
                body = sp.add_run(req.spec)
                body.font.size = Pt(8.5)
                body.font.color.rgb = RGBColor.from_string(INK_HEX)
            if req.detail:
                dp = row[2].add_paragraph() if req.spec else sp
                drun = dp.add_run(req.detail)
                drun.font.size = Pt(8.5)
                drun.font.color.rgb = RGBColor.from_string(INK_HEX)
            if not req.spec and not req.detail:
                _docx_set(row[2], "-", size=8.5, color=MUTED_HEX)
            cite = " - ".join(p_ for p_ in (req.code_ref, req.page_ref) if p_)
            _docx_set(row[3], cite or "-", size=7.5, italic=True, color=MUTED_HEX)
        _docx_fixed_layout(t, _DET_W)
        return t

    for prefix, ch in _all_chapters(r):
        counts = _chapter_counts(ch)
        if not counts["total"]:
            continue
        doc.add_paragraph()
        _docx_chapter_bar(doc, f"{prefix}{ch.chapter_code}  |  {ch.chapter_title}",
                          f"{counts['total']} items · {counts['required']} req.")
        if ch.selected_branch:
            _docx_para(doc, f"Governing table / row: {branch_label(ch)}",
                       size=8, italic=True, color=MUTED_HEX, space_before=3, space_after=3)
        if not prefix:
            for fig in figures_for(ch.chapter_code):
                _add_docx_figure(doc, fig, width_in=5.9)
        for block in ch.blocks:
            if not block.items:
                continue
            _docx_section_head(doc, block.title)
            req_table(block.items)

    if r.high_ceiling and r.high_ceiling.applies:
        hc = r.high_ceiling
        doc.add_paragraph()
        _docx_chapter_bar(doc, "FP  |  High Ceiling Sprinkler Design (Table 9.29.A)", "")
        doc.add_paragraph()
        _docx_kv_table(doc, _high_ceiling_rows(hc))
        if hc.note:
            _docx_para(doc, f"Note: {hc.note}", size=8, italic=True, color=MUTED_HEX)

    _docx_disclaimer(doc)

    buf = BytesIO()
    doc.save(buf)
    return buf.getvalue()


