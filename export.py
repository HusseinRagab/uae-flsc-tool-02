_GOVERNING_KEYWORDS = {
    "FSA": ("Extent of fire vehicle access",),
    "MOE": ("Number of Means of Egress", "Primary and Secondary Means"),
    "FE": ("Class A Fire Extinguisher", "Class K Fire Extinguisher", "Class B Fire Extinguisher"),
    "ES": ("Exit Signs at Exit Doors", "Exit Sign"),
    "FA": ("Smoke Detection and Alarm System", "Heat Detection and Alarm System",
           "Manual Fire Detection", "Fire Detection and Alarm"),
    "FP": ("Automatic Sprinkler System", "Wet Riser", "Hose Reel System", "Fire Pump"),
}
# FP also states the pump and the tank on the same line: they size the water supply.
_FP_COMPANIONS = ("Fire Pump", "Fire Water Tank")


def _is_placeholder(it) -> bool:
    return "NOT EVALUATED" in (it.system or "")


def governing_rows(r: ComplianceReport) -> list:
    """(chapter, system, spec, citation, required_count) per chapter: the line that
    governs the chapter's design, chosen by the chapter's headline system, else the
    matched branch's own first required line, else the first required line. Text is
    never cut; NOT EVALUATED placeholders are not chosen as the headline but are
    counted and named."""
    rows = []
    for ch in r.chapters:
        req = []
        seen = set()
        for blk in ch.blocks:
            for it in blk.items:
                if it.status == "required" and it.system not in seen:
                    seen.add(it.system)
                    req.append(it)
        if not req:
            continue
        real = [it for it in req if not _is_placeholder(it)]
        pick = None
        for kw in _GOVERNING_KEYWORDS.get(ch.chapter_code, ()):
            pick = next((it for it in real if it.system.startswith(kw)), None) \
                or next((it for it in real if kw.lower() in it.system.lower()), None)
            if pick:
                break
        if pick is None:
            pick = next((it for it in real if it.source_rule and it.source_rule == ch.selected_branch),
                        None) or (real[0] if real else req[0])
        spec = pick.spec or ""
        if ch.chapter_code == "FSA" and r.fire_access and r.fire_access.extent:
            spec = r.fire_access.extent
        if ch.chapter_code == "MOE" and r.occupant_load:
            spec = _ol_text(r.occupant_load)
        if ch.chapter_code == "FP":
            extra = []
            for comp in _FP_COMPANIONS:
                c = next((it for it in real if it.system.startswith(comp) and it is not pick), None)
                if c and c.spec:
                    extra.append(f"{c.system}: {c.spec}")
            spec = "; ".join(x for x in [spec] + extra if x)
        missing = [it.system for it in req if _is_placeholder(it)]
        if missing:
            spec = (spec + "; " if spec else "") + f"{len(missing)} line(s) NOT EVALUATED: " \
                + ", ".join(missing)
        cite = " - ".join(p for p in (pick.code_ref, pick.page_ref) if p)
        rows.append((ch.chapter_code, pick.system, spec or "-", cite or "-", len(req)))
    return rows


