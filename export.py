"""UAE FLSC 2018 - Word (.docx), PDF and Excel exporters - multi-chapter.

One shared visual identity across every export, taken from the compact PDF:
teal + paper palette, first-page banner with a thin strip on later pages,
footer with edition + page number, teal chapter bars with counts, outlined
requirement-count chips and a consistent type hierarchy. The Word renderers
mirror the PDF design as closely as python-docx allows so a compact PDF, a
detailed Word file and an executive summary all read as one report family.

NOTE ON LAZY IMPORTS: python-docx / reportlab / openpyxl are deliberately
imported inside the renderer functions, not at module top. app.py imports
this module unconditionally and its UI degrades gracefully (a per-button
warning) when an optional export dependency is missing; a top-level import
would take the whole app down instead. Keep it this way.
"""
from __future__ import annotations

