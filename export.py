# Shown on every report whatever their value: the geometry that routes every table.
_CORE_FIELDS = ("occupancy", "height_m", "height_datum", "floors_above_grade",
                "floors_below_grade", "ground_floor_bua_m2", "gross_floor_area_m2",
                "plot_area_m2", "hazard_class")


def field_label(name: str) -> str:
    if name in FIELD_LABELS:
        return FIELD_LABELS[name]
    stem = re.sub(r"^(has_|is_)", "", name).replace("_", " ")
    return stem[:1].upper() + stem[1:]


def _fmt_value(name, v) -> str:
    if isinstance(v, bool):
        return "Yes"
    if isinstance(v, float):
        return f"{v:,.2f}".rstrip("0").rstrip(".") if v != int(v) else f"{v:,.0f}"
    if isinstance(v, int):
        return f"{v:,}"
    if isinstance(v, (list, tuple)):
        parts = []
        for x in v:
            d = x.model_dump() if hasattr(x, "model_dump") else x
            if isinstance(d, dict):
                bits = [str(d.get("storey") or "").strip(), str(d.get("row") or "").strip()]
                area = d.get("area_m2")
                if area is not None:
                    bits.append(f"{float(area):,.0f} m2")
                if d.get("count") not in (None, 1):
                    bits.append(f"x{d['count']}")
                parts.append(" ".join(b for b in bits if b))
            else:
                parts.append(OCCUPANCY_DEFS.get(str(d), str(d)).split(" - ")[0]
                             if name == "secondary_occupancies" else str(d))
        return "; ".join(parts)
    if name == "occupancy":
        return OCCUPANCY_DEFS.get(v, v).split(" - ")[0] + f" ({v})"
    return str(v).replace("_", " ")


def inputs_rows(b, requires_wet_riser: bool | None = None) -> list:
    """(label, value) for every input that drives the report: the core geometry
    always, every ticked box, every non-zero number and every choice made, including
    the choices that stayed on their default where they apply (audit UX-12,
    28.10.2026). Blank (None) parking inputs are listed as 'not entered'."""
    rows = []
    occ = getattr(b, "occupancy", "")
    parking = bool(getattr(b, "has_parking_area", False))
    # Choices that apply only in context: listed (default or not) where they apply.
    contextual = {
        "attached_parking_kind": parking,
        "motor_fuel_group": occ == "motor_fuel_dispensing",
        "hangar_group": bool(getattr(b, "is_aircraft_hanger", False)),
        "wet_riser_standpipes": bool(requires_wet_riser),
        "tunnel_kind": bool(getattr(b, "has_tunnel", False)),
        "storage_commodity": occ == "storage_industrial",
    }
    for name, f in type(b).model_fields.items():
        if name == "project_name":
            continue
        v = getattr(b, name, None)
        if name in _CORE_FIELDS:
            rows.append((field_label(name), _fmt_value(name, v)))
            continue
        if name in contextual:
            if contextual[name]:
                rows.append((field_label(name), _fmt_value(name, v)))
            continue
        if isinstance(v, bool):
            if v:
                rows.append((field_label(name), "Yes"))
            elif f.default is True:
                rows.append((field_label(name), "No (unticked)"))
            continue
        if v is None:
            # A blank parking input is named, never dropped (a blank is not a pass).
            if name.startswith("parking_") and parking:
                rows.append((field_label(name), "not entered"))
            continue
        if isinstance(v, (int, float)) and v == 0:
            continue
        if isinstance(v, (list, tuple)) and not v:
            continue
        if isinstance(v, str) and (v == f.default or v in ("none", "unspecified")):
            continue
        if name == "exit_stairs" and v == f.default:
            continue
        rows.append((field_label(name), _fmt_value(name, v)))
    return rows


def default_meta(r) -> dict:
    return {"notes": "", "generated": _dt.datetime.now().strftime("%Y-%m-%d %H:%M"),
            "revision": tool_revision(),
            "inputs": inputs_rows(r.building, getattr(r, "requires_wet_riser", None)),
            "assumptions": []}


def _meta(r, meta) -> dict:
    m = default_meta(r)
    for k, v in (meta or {}).items():
        if v is not None:
            m[k] = v
    m["inputs"] = [tuple(x) for x in (m.get("inputs") or [])]
    m["assumptions"] = list(m.get("assumptions") or [])
    return m


def stamp_text(m: dict) -> str:
    return f"Generated {m['generated']}  |  FLSC tool revision {m['revision']}"


def export_file_name(project: str, kind: str, ext: str, date: str | None = None) -> str:
    """<project>_FLSC_<kind>_<YYYY-MM-DD>.<ext> (audit UX-12)."""
    stem = re.sub(r"[^A-Za-z0-9._-]+", "_", (project or "building").strip()).strip("_") or "building"
    date = date or _dt.date.today().isoformat()
    return f"{stem}_FLSC_{kind}_{date}.{ext}"


