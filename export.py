def report_to_pdf_bytes(r: ComplianceReport, kind: str = "detailed") -> bytes:
    if kind == "compact":
        return _compact_pdf(r)
    if kind == "executive":
        return _executive_pdf(r)
    return _detailed_pdf(r)


def _pdf_palette():
    from reportlab.lib import colors
    pal = {
        "TEAL": colors.HexColor(f"#{TEAL_HEX}"),
        "PAPER": colors.HexColor(f"#{PAPER_HEX}"),
        "PAPER_TINT": colors.HexColor(f"#{PAPER_TINT_HEX}"),
        "INK": colors.HexColor(f"#{INK_HEX}"),
        "MUTED": colors.HexColor(f"#{MUTED_HEX}"),
        "RULE": colors.HexColor(f"#{RULE_HEX}"),
        "WHITE": colors.white,
    }
    for s, hx in STATUS_HEX.items():
        pal[s] = colors.HexColor(f"#{hx}")
    return pal


