def _pdf_chrome(r: ComplianceReport, kind: str, pagesize):
    """(onFirstPage, onLaterPages) painters — teal banner on page 1, thin strip
    + running header on later pages, shared footer with edition + page no."""
    P = _pdf_palette()
    W, H = pagesize
    b = r.building
    subtitle, short = KIND_META.get(kind, KIND_META["detailed"])

    def _footer(c, doc):
        c.saveState()
        c.setStrokeColor(P["RULE"])
        c.setLineWidth(0.4)
        c.line(48, 30, W - 48, 30)
        c.setFillColor(P["MUTED"])
        c.setFont("Helvetica", 7)
        c.drawString(48, 18, f"UAE FLSC 2018  |  {EDITION}  |  {short} report")
        c.drawRightString(W - 48, 18, f"Page {doc.page}")
        c.restoreState()

    def _later(c, doc):
        c.saveState()
        c.setFillColor(P["TEAL"])
        c.rect(0, H - 7, W, 7, fill=1, stroke=0)
        c.setFillColor(P["MUTED"])
        c.setFont("Helvetica", 7)
        name = (b.project_name or "Fire & life safety report")[:72]
        c.drawString(48, H - 20, f"{name}  |  {short}")
        c.restoreState()
        _footer(c, doc)

    def _first(c, doc):
        c.saveState()
        c.setFillColor(P["PAPER"])
        c.rect(0, 0, W, H, fill=1, stroke=0)
        c.setFillColor(P["TEAL"])
        c.rect(0, H - 96, W, 96, fill=1, stroke=0)
        c.setFillColor(P["WHITE"])
        c.setFont("Helvetica-Bold", 15)
        c.drawString(48, H - 50, BRAND_TITLE)
        c.setFillColor(P["PAPER"])
        c.setFont("Helvetica", 9)
        c.drawString(48, H - 70, f"{EDITION}  |  {subtitle}")
        c.restoreState()
        _footer(c, doc)

    return _first, _later


def _pdf_profile_table(rows, styles, label_w, value_w):
    from reportlab.platypus import Paragraph, Table, TableStyle
    from reportlab.lib.units import cm
    pt = Table([[Paragraph(k, styles["k"]), Paragraph(str(v), styles["v"])]
                for k, v in rows],
               colWidths=[label_w * cm, value_w * cm])
    pt.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 1.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 1.5),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
    ]))
    return pt


def _pdf_status_chips(tot, styles, chip_w=3.9, slot_w=4.2):
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.platypus import Paragraph, Table, TableStyle
    from reportlab.lib.units import cm
    P = _pdf_palette()
    chip_cells = []
    for s in STATUS_ORDER:
        col = P[s]
        lab = ParagraphStyle(f"chip_l_{s}", fontName="Helvetica-Bold", fontSize=7,
                             textColor=col, leading=9)
        num = ParagraphStyle(f"chip_n_{s}", fontName="Helvetica-Bold", fontSize=14,
                             textColor=P["INK"], leading=16)
        inner = Table([[Paragraph(STATUS_LABEL[s], lab)],
                       [Paragraph(str(tot.get(s, 0)), num)]],
                      colWidths=[chip_w * cm])
        inner.setStyle(TableStyle([
            ("BOX", (0, 0), (-1, -1), 1.1, col),
            ("BACKGROUND", (0, 0), (-1, -1), P["WHITE"]),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
            ("TOPPADDING", (0, 0), (0, 0), 5),
            ("BOTTOMPADDING", (0, -1), (-1, -1), 5),
        ]))
        chip_cells.append(inner)
    chips = Table([chip_cells], colWidths=[slot_w * cm] * 4)
    chips.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 2),
        ("RIGHTPADDING", (0, 0), (-1, -1), 2),
    ]))
    return chips


def _pdf_chapter_bar(left_text, right_text, styles, total_w):
    from reportlab.platypus import Paragraph, Table, TableStyle
    from reportlab.lib.units import cm
    P = _pdf_palette()
    bar = Table(
        [[Paragraph(left_text, styles["chbar"]),
          Paragraph(right_text, styles["chnum"])]],
        colWidths=[(total_w - 3.4) * cm, 3.4 * cm],
    )
    bar.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), P["TEAL"]),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    return bar


def _rl_figure(fig, max_w, max_h):
    from reportlab.platypus import Image as RLImage, Paragraph, Spacer
    path = fig["path"]
    if not path.exists():
        return []
    styles = _pdf_styles()
    img = RLImage(str(path))
    iw, ih = float(img.imageWidth), float(img.imageHeight)
    scale = min(max_w / iw, max_h / ih)
    img.drawWidth = iw * scale
    img.drawHeight = ih * scale
    return [img, Spacer(1, 4),
            Paragraph(figure_caption(fig).replace("—", "-"), styles["ital"])]


def _compact_pdf(r: ComplianceReport) -> bytes:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import cm
    from reportlab.platypus import (
        SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable,
    )

    P = _pdf_palette()
    styles = _pdf_styles()
    b = r.building
    tot = _status_totals(r)
    inner = 16.8  # usable width in cm at 48pt margins

    story = [Spacer(1, 58)]
    story.append(Paragraph(b.project_name or "Fire & life safety report", styles["title"]))
    story.append(Paragraph("Building profile", styles["sec"]))
    story.append(_pdf_profile_table(_profile_rows(r), styles, 4.4, 12.4))
    story.append(Spacer(1, 6))
    story.append(HRFlowable(width="100%", thickness=0.5, color=P["RULE"], spaceAfter=8))
    story.append(Paragraph("Requirement counts", styles["sec"]))
    story.append(_pdf_status_chips(tot, styles))
    story.append(Spacer(1, 8))
    story.append(Paragraph("Required systems  -  headers only", styles["sec"]))

    for prefix, ch in _all_chapters(r):
        items = _required_systems(ch)
        if not items:
            continue
        story.append(Spacer(1, 5))
        story.append(_pdf_chapter_bar(
            f"{prefix}{ch.chapter_code}  |  {ch.chapter_title}",
            f"{len(items)} required", styles, inner))
        names = [Paragraph("•  " + it.system, styles["item"]) for it in items]
        body = Table([[p] for p in names], colWidths=[inner * cm])
        body.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 10),
            ("RIGHTPADDING", (0, 0), (-1, -1), 4),
            ("TOPPADDING", (0, 0), (-1, -1), 1),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 1),
            ("LINEBEFORE", (0, 0), (0, -1), 2.2, P["TEAL"]),
            ("BACKGROUND", (0, 0), (-1, -1), P["WHITE"]),
        ]))
        story.append(body)

    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", thickness=0.4, color=P["RULE"], spaceAfter=6))
    story.append(Paragraph("Compact export. Use the Detailed PDF for figures and full clauses.", styles["small"]))
    story.append(Paragraph(DISCLAIMER, styles["ital"]))

    buf = BytesIO()
    _first, _later = _pdf_chrome(r, "compact", A4)
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=48, rightMargin=48, topMargin=40, bottomMargin=42,
        title=f"{b.project_name or 'UAE FLSC'} - compact Fire & Life Safety report",
    )
    doc.build(story, onFirstPage=_first, onLaterPages=_later)
    return buf.getvalue()


def _detailed_pdf(r: ComplianceReport) -> bytes:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import cm
    from reportlab.platypus import (
        SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable,
    )

    P = _pdf_palette()
    styles = _pdf_styles()
    b = r.building
    tot = _status_totals(r)
    inner = 17.5  # usable width in cm at 48pt margins (A4 portrait)

    story = [Spacer(1, 58)]
    story.append(Paragraph(b.project_name or "Fire & life safety report", styles["title"]))
    story.append(Paragraph("Building profile", styles["sec"]))
    story.append(_pdf_profile_table(_profile_rows(r, detailed=True), styles, 4.6, 12.9))
    story.append(Spacer(1, 6))
    story.append(HRFlowable(width="100%", thickness=0.5, color=P["RULE"], spaceAfter=8))
    story.append(Paragraph("Requirement counts", styles["sec"]))
    story.append(_pdf_status_chips(tot, styles, chip_w=4.05, slot_w=4.375))

    def req_table(items: List[Requirement]):
        data = [[Paragraph("System", styles["hdr"]),
                 Paragraph("Spec / Detail", styles["hdr"]),
                 Paragraph("Code Ref", styles["hdr"])]]
        for req in items:
            tag = ""
            if req.status != "required":
                tag = (f' <font color="#{STATUS_HEX[req.status]}">'
                       f'[{STATUS_LABEL[req.status].lower()}]</font>')
            sys_p = Paragraph(f"<b>{req.system}</b>{tag}", styles["cell"])
            parts = []
            if req.spec:
                parts.append(f"<b>Spec:</b> {req.spec}")
            if req.detail:
                parts.append(req.detail)
            spec_p = Paragraph("<br/><br/>".join(parts) if parts else "-", styles["cell"])
            cite_t = " - ".join(p for p in (req.code_ref, req.page_ref) if p)
            cite_p = Paragraph(cite_t or "-", styles["cite"])
            data.append([sys_p, spec_p, cite_p])
        t = Table(data, colWidths=[4.3 * cm, 9.4 * cm, 3.8 * cm], repeatRows=1)
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), P["TEAL"]),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [P["WHITE"], P["PAPER_TINT"]]),
            ("LINEBELOW", (0, 0), (-1, -2), 0.4, P["RULE"]),
            ("BOX", (0, 0), (-1, -1), 0.6, P["RULE"]),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        return t

    for prefix, ch in _all_chapters(r):
        counts = _chapter_counts(ch)
        if not counts["total"]:
            continue
        story.append(Spacer(1, 10))
        story.append(_pdf_chapter_bar(
            f"{prefix}{ch.chapter_code}  |  {ch.chapter_title}",
            f"{counts['total']} items · {counts['required']} req.",
            styles, inner))
        story.append(Spacer(1, 4))
        if ch.selected_branch:
            story.append(Paragraph(
                f"Matched branch: {ch.selected_branch}  -  {ch.selected_branch_section}",
                styles["branch"]))
        if not prefix:
            for fig in figures_for(ch.chapter_code):
                story.extend(_rl_figure(fig, 15 * cm, 8.5 * cm))
        for block in ch.blocks:
            if not block.items:
                continue
            story.append(Paragraph(block.title, styles["sec"]))
            story.append(req_table(block.items))
            story.append(Spacer(1, 6))

    if r.high_ceiling and r.high_ceiling.applies:
        hc = r.high_ceiling
        story.append(Spacer(1, 10))
        story.append(_pdf_chapter_bar(
            "FP  |  High Ceiling Sprinkler Design (Table 9.29.A)", "", styles, inner))
        story.append(Spacer(1, 4))
        story.append(_pdf_profile_table(_high_ceiling_rows(hc), styles, 4.6, 12.9))
        if hc.note:
            story.append(Paragraph(f"Note: {hc.note}", styles["ital"]))

    story.append(Spacer(1, 14))
    story.append(HRFlowable(width="100%", thickness=0.4, color=P["RULE"], spaceAfter=6))
    story.append(Paragraph(DISCLAIMER, styles["ital"]))
    story.append(Paragraph(GENERATED_NOTE, styles["small"]))

    buf = BytesIO()
    _first, _later = _pdf_chrome(r, "detailed", A4)
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=48, rightMargin=48, topMargin=40, bottomMargin=42,
        title=f"{b.project_name or 'UAE FLSC'} - detailed Fire & Life Safety report",
    )
