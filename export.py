def _pdf_chrome(r: ComplianceReport, kind: str, pagesize, m: dict | None = None):
    """(onFirstPage, onLaterPages) painters — teal banner on page 1, thin strip
    + running header on later pages, shared footer with edition + page no."""
    P = _pdf_palette()
    W, H = pagesize
    b = r.building
    subtitle, short = KIND_META.get(kind, KIND_META["detailed"])

    def _footer(c, doc):
        c.saveState()
        c.setStrokeColor(P["RULE"])
        c.setLineWidth(0.4)
        c.line(48, 36, W - 48, 36)
        c.setFillColor(P["MUTED"])
        c.setFont("Helvetica", 7)
        c.drawString(48, 26, f"UAE FLSC 2018  |  {EDITION}  |  {short} report")
        if m:
            c.drawString(48, 16, stamp_text(m))
        c.drawRightString(W - 48, 26, f"Page {doc.page}")
        c.restoreState()

    def _later(c, doc):
        c.saveState()
        c.setFillColor(P["TEAL"])
        c.rect(0, H - 7, W, 7, fill=1, stroke=0)
        c.setFillColor(P["MUTED"])
        c.setFont("Helvetica", 7)
        name = (b.project_name or "Fire & life safety report")[:72]
        c.drawString(48, H - 20, f"{name}  |  {short}")
        c.restoreState()
        _footer(c, doc)

    def _first(c, doc):
        c.saveState()
        c.setFillColor(P["PAPER"])
        c.rect(0, 0, W, H, fill=1, stroke=0)
        c.setFillColor(P["TEAL"])
        c.rect(0, H - 96, W, 96, fill=1, stroke=0)
        c.setFillColor(P["WHITE"])
        c.setFont("Helvetica-Bold", 15)
        c.drawString(48, H - 50, BRAND_TITLE)
        c.setFillColor(P["PAPER"])
        c.setFont("Helvetica", 9)
        c.drawString(48, H - 70, f"{EDITION}  |  {subtitle}")
        c.restoreState()
        _footer(c, doc)

    return _first, _later


