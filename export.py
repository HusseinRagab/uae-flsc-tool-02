@functools.lru_cache(maxsize=1)
def tool_revision() -> str:
    """Short git commit of the tool that produced the report ('unknown' when the
    code is not a git checkout), printed on every export so a reviewer can tell
    which revision of the rules gave the result."""
    here = Path(__file__).resolve().parent
    try:
        out = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=here,
                             capture_output=True, text=True, timeout=3)
        sha = out.stdout.strip()
        if out.returncode == 0 and re.fullmatch(r"[0-9a-f]{4,40}", sha):
            return sha
    except Exception:
        pass
    try:   # no git binary: read .git/HEAD directly
        head = (here / ".git" / "HEAD").read_text(encoding="utf-8").strip()
        if head.startswith("ref:"):
            ref = here / ".git" / head.split(" ", 1)[1].strip()
            head = ref.read_text(encoding="utf-8").strip()
        if re.fullmatch(r"[0-9a-f]{7,40}", head):
            return head[:7]
    except Exception:
        pass
    return "unknown"


