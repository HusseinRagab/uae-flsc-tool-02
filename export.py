    from reportlab.lib.units import cm
    from reportlab.platypus import (
        SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable,
    )

    P = _pdf_palette()
    styles = _pdf_styles()
    b = r.building
    tot = _status_totals(r)
    inner = 16.8  # usable width in cm at 48pt margins

    story = [Spacer(1, 58)]
