def _docx_kv_table(doc, rows, label_w=4.4, value_w=13.0):
    tbl = doc.add_table(rows=len(rows), cols=2)
    _docx_table_borders(tbl, RULE_HEX, size=4)
    _docx_fixed_layout(tbl, [label_w, value_w])
    for i, (k, v) in enumerate(rows):
        _docx_shade(tbl.rows[i].cells[0], PAPER_HEX)
        _docx_set(tbl.rows[i].cells[0], k, size=8.5, bold=True, color=MUTED_HEX)
        _docx_set(tbl.rows[i].cells[1], str(v), size=9.5, color=INK_HEX)
    return tbl


