    doc.add_paragraph()

    _docx_para(doc, b.project_name or "Fire & life safety report",
               size=15, bold=True, color=INK_HEX, space_after=6)

    # ---- Running footer: edition | kind · page number field ----
    footer = section.footer
    fp = footer.paragraphs[0]
    fp.text = ""
