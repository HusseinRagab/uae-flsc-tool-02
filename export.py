    ws = wb.active
    ws.title = "Systems"
    headers = ["Chapter", "Chapter title", "Block", "System", "Status",
               "Spec", "Detail", "Code ref", "Page", "Source rule"]
    ws.append(headers)
    hf = Font(bold=True, color="FFFFFF")
    hfill = PatternFill("solid", fgColor=TEAL_HEX)
    for col, _ in enumerate(headers, 1):
        c = ws.cell(1, col)
        c.font = hf
        c.fill = hfill
